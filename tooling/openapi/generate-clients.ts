import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import {
  ensureDir,
  ensureParentDir,
  fromRoot,
  FR_ROOT,
  loadServices,
  selectServices,
  type OpenApiService,
} from './common';

const GENERATED_CONFIG_FILE = fromRoot('tooling/openapi/orval.generated.ts');
/** Normalises header parameters before orval sees them (see the file). */
const TRANSFORMER = fromRoot('tooling/openapi/transform.cjs');

function packageJsonFor(service: OpenApiService): string {
  return JSON.stringify(
    {
      name: `@fr/service-client-${service.name}`,
      private: true,
      type: 'module',
      main: './src/index.ts',
      module: './src/index.ts',
      types: './src/index.ts',
      exports: {
        '.': {
          types: './src/index.ts',
          default: './src/index.ts',
        },
        // Upstream data artifacts: a SUBPATH, never the barrel, so production
        // code that imports the client does not pick up a fallback dataset.
        ...Object.fromEntries(
          (service.artifacts ?? []).map((a) => [
            `./${a.name}`,
            { types: `./src/generated/${a.name}.ts`, default: `./src/generated/${a.name}.ts` },
          ]),
        ),
      },
    },
    null,
    2,
  ) + '\n';
}

const INDEX_BARREL =
  '// Re-export the Orval-generated client surface. Hand-written code does not\n' +
  '// belong in this package — when the upstream OpenAPI spec changes, run\n' +
  '// `bun run openapi:sync && bun run clients:generate` to refresh `generated/`.\n' +
  "export * from './generated/client';\n" +
  "export * from './generated/models';\n" +
  "export * from './generated/put-body-properties';\n" +
  "export * from './generated/operations';\n";

function buildOrvalEntry(service: OpenApiService): string {
  const snapshotPath = fromRoot(service.snapshotFile);
  const clientDir = fromRoot(service.clientDir);
  const target = join(clientDir, 'src/generated/client.ts');
  const schemas = join(clientDir, 'src/generated/models');

  return `  ${JSON.stringify(service.name)}: {
    input: {
      target: ${JSON.stringify(snapshotPath)},
      override: { transformer: ${JSON.stringify(TRANSFORMER)} }
    },
    output: {
      target: ${JSON.stringify(target)},
      schemas: ${JSON.stringify(schemas)},
      client: 'fetch',
      headers: true,
      mode: 'single',
      clean: true
    }
  }`;
}

async function ensureServiceScaffold(service: OpenApiService): Promise<void> {
  const clientDir = fromRoot(service.clientDir);
  await ensureDir(join(clientDir, 'src/generated'));
  await ensureParentDir(join(clientDir, 'package.json'));
  await writeFile(join(clientDir, 'package.json'), packageJsonFor(service), 'utf8');
  await writeFile(join(clientDir, 'src/index.ts'), INDEX_BARREL, 'utf8');
}

/**
 * `src/generated/put-body-properties.ts`: for every PUT operation whose request
 * body is a named component schema, that schema's property names — the RUNTIME
 * twin of the generated `*In` interfaces, which are erased at compile time.
 *
 * fr's read-modify-write over a replacing PUT (`backend/src/integrations/_lib/
 * merge-update.ts`) lifts exactly these keys off the stored row, so a field the
 * upstream gains is carried through untouched the moment the snapshot is
 * regenerated — no hand-kept field list to forget. Written after orval (whose
 * `clean: true` empties the directory) and diffed by `--check` like the rest.
 */
async function writePutBodyProperties(service: OpenApiService): Promise<void> {
  type Schema = { properties?: Record<string, unknown> };
  const spec = (await Bun.file(fromRoot(service.snapshotFile)).json()) as {
    paths?: Record<string, { put?: { requestBody?: { content?: Record<string, { schema?: { $ref?: string } }> } } }>;
    components?: { schemas?: Record<string, Schema> };
  };
  const out: Record<string, string[]> = {};
  for (const op of Object.values(spec.paths ?? {})) {
    const ref = op.put?.requestBody?.content?.['application/json']?.schema?.$ref;
    const name = ref?.startsWith('#/components/schemas/') ? ref.slice('#/components/schemas/'.length) : undefined;
    const schema = name ? spec.components?.schemas?.[name] : undefined;
    if (!name || !schema?.properties) continue;
    out[name] = Object.keys(schema.properties).sort();
  }
  const lines = Object.keys(out)
    .sort()
    .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(out[name])},`);
  const content =
    `// Generated by tooling/openapi/generate-clients.ts from ${service.snapshotFile}.\n` +
    '// Do not edit manually. For every PUT whose body is a named schema: its property names.\n' +
    `export const PUT_BODY_PROPERTIES = {\n${lines.join('\n')}\n} as const;\n\n` +
    'export type PutBodySchemaName = keyof typeof PUT_BODY_PROPERTIES;\n';
  await writeFile(join(fromRoot(service.clientDir), 'src/generated/put-body-properties.ts'), content, 'utf8');
}

/**
 * `src/generated/operations.ts`: every operation of the snapshot keyed by the
 * name orval gives it (`get<Name>Url` is its URL builder). The RUNTIME twin of the
 * generated client's per-operation types (erased at compile time) — method, path,
 * query and header parameter names, the named request-body schema — so fr code
 * that is driven by a table of upstream operations (backend
 * routes/assets/_lib/rm-passthrough.ts) reads the upstream's own declaration
 * instead of a hand-kept copy. Written after orval and diffed by `--check`.
 */
async function writeOperations(service: OpenApiService): Promise<void> {
  type Param = { name?: string; in?: string; $ref?: string };
  type Op = {
    operationId?: string;
    parameters?: Param[];
    requestBody?: { content?: Record<string, { schema?: { $ref?: string } }> };
  };
  const spec = (await Bun.file(fromRoot(service.snapshotFile)).json()) as {
    paths?: Record<string, Record<string, Op>>;
    components?: { parameters?: Record<string, Param> };
  };
  const client = await readFile(join(fromRoot(service.clientDir), 'src/generated/client.ts'), 'utf8');
  const resolve = (p: Param): Param =>
    p.$ref?.startsWith('#/components/parameters/') ? (spec.components?.parameters?.[p.$ref.slice(23)] ?? p) : p;
  const lines: string[] = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const method of ['get', 'post', 'put', 'patch', 'delete'] as const) {
      const op = item?.[method];
      if (!op?.operationId) continue;
      const name = op.operationId
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((w, i) => (i === 0 ? w.charAt(0).toLowerCase() + w.slice(1) : w.charAt(0).toUpperCase() + w.slice(1)))
        .join('');
      // Only operations orval generated a URL builder for, under the name computed here.
      if (!client.includes(`export const get${name.charAt(0).toUpperCase()}${name.slice(1)}Url =`)) continue;
      const params = (op.parameters ?? []).map(resolve);
      const query = params.filter((p) => p.in === 'query' && p.name).map((p) => p.name as string);
      const headers = params.filter((p) => p.in === 'header' && p.name).map((p) => p.name as string);
      const content = op.requestBody?.content ?? {};
      const ref = Object.values(content)[0]?.schema?.$ref;
      const body = ref?.startsWith('#/components/schemas/') ? ref.slice('#/components/schemas/'.length) : undefined;
      const entry: Record<string, unknown> = { method: method.toUpperCase(), path, query, headers };
      if (body !== undefined) entry.body = body;
      lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(entry)},`);
    }
  }
  lines.sort();
  const content =
    `// Generated by tooling/openapi/generate-clients.ts from ${service.snapshotFile}.\n` +
    '// Do not edit manually. Every operation, keyed by its generated name (`get<Name>Url`).\n' +
    `export const OPERATIONS = {\n${lines.join('\n')}\n} as const;\n\n` +
    'export type OperationName = keyof typeof OPERATIONS;\n';
  await writeFile(join(fromRoot(service.clientDir), 'src/generated/operations.ts'), content, 'utf8');
}

/**
 * `src/generated/<artifact>.ts`: the upstream data artifact snapshotted by
 * sync-specs.ts (VERBATIM JSON under tooling/openapi/specs/), as a typed module.
 * Written after orval (whose `clean: true` empties the directory) and diffed by
 * `--check` like the rest, so a hand edit here or a snapshot changed without
 * regenerating fails the gate.
 */
async function writeArtifacts(service: OpenApiService): Promise<void> {
  for (const artifact of service.artifacts ?? []) {
    const data = JSON.parse(await readFile(fromRoot(artifact.snapshotFile), 'utf8')) as unknown;
    const content =
      `// Generated by tooling/openapi/generate-clients.ts from ${artifact.snapshotFile}\n` +
      `// = ${artifact.repo}@${artifact.ref}:${artifact.path} (refresh: \`bun run openapi:sync ${service.name}\`).\n` +
      '// Do not edit manually.\n' +
      `export const ${artifact.exportName} = ${JSON.stringify(data, null, 2)};\n`;
    await writeFile(join(fromRoot(service.clientDir), `src/generated/${artifact.name}.ts`), content, 'utf8');
  }
}

async function writeGeneratedConfig(services: OpenApiService[]): Promise<void> {
  const entries = services.map(buildOrvalEntry).join(',\n');
  const content = `export default {
${entries}
};
`;

  await ensureParentDir(GENERATED_CONFIG_FILE);
  await writeFile(GENERATED_CONFIG_FILE, content, 'utf8');
}

// The orval that generates the committed clients is the one backend/package.json
// pins EXACTLY. `bunx orval` from the repo root (which has no node_modules) would
// fetch whatever orval is latest on the registry, so the same snapshot could
// produce different code on two machines and the drift gate would flap.
const ORVAL_BIN = fromRoot('backend/node_modules/.bin/orval');

async function assertPinnedOrval(): Promise<void> {
  const pkg = (await Bun.file(fromRoot('backend/package.json')).json()) as {
    devDependencies?: Record<string, string>;
  };
  const pinned = pkg.devDependencies?.orval ?? '';
  if (!/^\d+\.\d+\.\d+$/.test(pinned)) {
    throw new Error(`backend/package.json must pin orval to an exact version (found "${pinned}")`);
  }
  const installedFile = Bun.file(fromRoot('backend/node_modules/orval/package.json'));
  if (!(await installedFile.exists())) {
    throw new Error('orval is not installed — run `bun install` in backend/ first');
  }
  const installed = ((await installedFile.json()) as { version: string }).version;
  if (installed !== pinned) {
    throw new Error(`installed orval ${installed} != pinned ${pinned} — run \`bun install\` in backend/`);
  }
}

function runOrval(): void {
  const tempDir = process.env.TMPDIR || '/tmp';
  const proc = Bun.spawnSync({
    cmd: [ORVAL_BIN, '--config', GENERATED_CONFIG_FILE],
    cwd: FR_ROOT,
    stdout: 'inherit',
    stderr: 'inherit',
    env: {
      ...process.env,
      TMPDIR: tempDir,
      TMP: tempDir,
      TEMP: tempDir,
    },
  });

  if (proc.exitCode !== 0) {
    throw new Error(`orval exited with code ${proc.exitCode}`);
  }
}

/** Every file under the services' client dirs, path → content. */
async function snapshotTree(services: OpenApiService[]): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  for (const service of services) {
    const dir = fromRoot(service.clientDir);
    for (const rel of await readdir(dir, { recursive: true })) {
      const file = join(dir, rel);
      if ((await stat(file)).isFile()) out.set(file, await readFile(file, 'utf8'));
    }
  }
  return out;
}

/**
 * `--check`: fail if regenerating changed, added or removed any file under the
 * client dirs (a hand edit under generated/, a snapshot changed without
 * regenerating, or an orval bump without regenerating). Compared against the
 * tree as it was BEFORE this run, so it holds locally and in CI alike.
 */
function assertNoDiff(before: Map<string, string>, after: Map<string, string>): void {
  const changed: string[] = [];
  for (const [file, content] of after) if (before.get(file) !== content) changed.push(`${before.has(file) ? 'changed' : 'added'}: ${file}`);
  for (const file of before.keys()) if (!after.has(file)) changed.push(`removed: ${file}`);
  if (changed.length > 0) {
    console.error('[clients:generate --check] the generated clients differ from what the committed snapshots produce:');
    for (const c of changed.slice(0, 50)) console.error(`  ${c.replace(`${FR_ROOT}/`, '')}`);
    if (changed.length > 50) console.error(`  … and ${changed.length - 50} more`);
    console.error('Run `bun run clients:generate` in backend/ and commit the result.');
    process.exit(1);
  }
  console.log(`[clients:generate --check] no drift (${after.size} generated files)`);
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const requestedNames = args.filter((a) => !a.startsWith('--'));
  const services = selectServices(await loadServices(), requestedNames);

  await assertPinnedOrval();
  const before = check ? await snapshotTree(services) : new Map<string, string>();
  for (const service of services) {
    await ensureServiceScaffold(service);
  }

  await writeGeneratedConfig(services);
  runOrval();
  for (const service of services) {
    await writePutBodyProperties(service);
    await writeOperations(service);
    await writeArtifacts(service);
  }
  if (check) assertNoDiff(before, await snapshotTree(services));
}

await main();
