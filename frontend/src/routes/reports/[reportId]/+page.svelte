<!--
  /reports/[reportId] — GET /api/reports/:reportId

  Backend: backend/src/routes/reports.ts:201. This handler returns the
  project_reports ROW BARE — no `{ data }` and no `{ items }` wrapper, unlike
  its four composed siblings. src/lib/api/reports.ts absorbs that difference.

  A cross-tenant id returns 404, not 403, deliberately (reports.ts:205-210) so
  ids cannot be probed across tenants. The error state therefore treats "not
  found" and "not yours" as the single answer the backend actually gives.

  ⚠️ This dynamic segment is a SIBLING of the static /reports/approval-backlog.
  SvelteKit prefers the static route, matching the backend's first-match
  registration order (server.ts:2074).
-->
<script lang="ts">
  import { page } from '$app/stores';
  import { setPageTitle } from '$lib/layout/pageTitle.svelte';
  import { getReport, type ProjectReport } from '$lib/api/reports';
  import ReportPanel from '$lib/components/reports/ReportPanel.svelte';
  import BugReportView from '$lib/components/reports/BugReportView.svelte';
  import { parseBugReportDetails } from '$lib/api/bug-report';

  const reportId = $derived($page.params.reportId ?? '');

  let report = $state<ProjectReport | undefined>(undefined);
  let loading = $state(true);
  let error = $state<string | undefined>(undefined);

  async function load(id: string): Promise<void> {
    loading = true;
    error = undefined;
    try {
      report = await getReport(id);
    } catch (e) {
      report = undefined;
      error = (e as Error).message;
    } finally {
      loading = false;
    }
  }

  $effect(() => {
    if (reportId) void load(reportId);
  });

  function fmtDate(iso: string | null | undefined): string {
    if (!iso) return '—';
    const t = Date.parse(iso);
    return Number.isFinite(t) ? new Date(t).toLocaleString() : iso;
  }

  /**
   * U2: a `bug_report` whose details have the bug_report/v1 shape gets the typed
   * renderer. Anything else — every other report type, or a bug_report that does
   * not parse — keeps the generic JSON view below.
   */
  const bugReport = $derived(
    report?.report_type === 'bug_report' ? parseBugReportDetails(report.details) : null,
  );

  /** `details` is free-form jsonb. Pretty-print rather than guess at a schema. */
  const detailsText = $derived(
    report?.details == null ? '' : JSON.stringify(report.details, null, 2),
  );

  const dt = 'text-xs uppercase tracking-wide text-[var(--color-text-muted)]';
  const dd = 'mt-0.5 text-sm text-[var(--color-text)]';

  // Publish this route's entity name to the single title element in the
  // root layout. Always the CURRENT pathname: the resolver drops an override
  // whose path no longer matches, which is what makes a stale tab title
  // impossible. `null` while loading falls back to the static map entry.
  $effect(() => {
    setPageTitle($page.url.pathname, report?.title ?? null);
  });
</script>

<div class="mx-auto max-w-4xl py-2">
  <header class="mb-4">
    <nav aria-label="Breadcrumb" class="text-xs text-[var(--color-text-muted)]">
      <a href="/reports" class="hover:underline">Reports</a>
      <span class="mx-1">/</span>
      <span>Stored report</span>
    </nav>
    <div class="mt-1 flex items-start justify-between gap-4">
      <h1 class="text-2xl font-semibold text-[var(--color-text)]">
        {report?.title ?? 'Stored report'}
      </h1>
      <button
        type="button"
        onclick={() => void load(reportId)}
        class="h-9 shrink-0 rounded-[var(--radius-md)] border border-[var(--color-border)] bg-[var(--color-surface)] px-3 text-sm text-[var(--color-text)] hover:bg-[var(--color-surface-strong)]"
      >
        Refresh
      </button>
    </div>
  </header>

  <ReportPanel
    label="this report"
    {loading}
    {error}
    empty={!report}
    emptyMessage="This report could not be found in your workspace. It may have been removed, or it belongs to another workspace."
    onRetry={() => void load(reportId)}
  >
    {#if report}
      <dl class="mb-6 grid grid-cols-2 gap-4 sm:grid-cols-4">
        <div>
          <dt class={dt}>Type</dt>
          <dd class={dd}>{report.report_type}</dd>
        </div>
        <div>
          <dt class={dt}>Generated by</dt>
          <dd class={dd}>{report.generated_by ?? '—'}</dd>
        </div>
        <div>
          <dt class={dt}>Created</dt>
          <dd class={dd}>{fmtDate(report.created_at)}</dd>
        </div>
        <div>
          <dt class={dt}>Project</dt>
          <dd class="mt-0.5 font-mono text-xs text-[var(--color-text)]">
            {#if report.project_id}
              <a data-testid="report-project-link" class="text-[var(--color-accent)] hover:underline" href={`/projects/${encodeURIComponent(report.project_id)}`}>{report.project_id}</a>
            {:else}
              —
            {/if}
            {#if report.card_id}
              <div class="mt-0.5">
                card <a data-testid="report-card-link" class="text-[var(--color-accent)] hover:underline" href={`/cards/${encodeURIComponent(report.card_id)}`}>{report.card_id}</a>
              </div>
            {/if}
          </dd>
        </div>
      </dl>

      <section class="mb-6">
        <h2 class="mb-1 text-sm font-semibold uppercase tracking-wide text-[var(--color-text-muted)]">
          Summary
        </h2>
        <p class="whitespace-pre-wrap text-sm text-[var(--color-text)]">{report.summary}</p>
      </section>

      {#if bugReport}
        <BugReportView details={bugReport} contentHash={report.content_hash ?? null} traceId={report.trace_id ?? null} />
      {:else}
      <section>
        <h2 class="mb-1 text-sm font-semibold uppercase tracking-wide text-[var(--color-text-muted)]">
          Details
        </h2>
        {#if detailsText}
          <pre
            data-testid="report-details"
            class="overflow-x-auto rounded-[var(--radius-md)] border border-[var(--color-border)] bg-[var(--color-surface)] p-3 text-xs text-[var(--color-text)]">{detailsText}</pre>
        {:else}
          <p class="text-sm text-[var(--color-text-muted)]">
            This report carries no structured details.
          </p>
        {/if}
      </section>
      {/if}
    {/if}
  </ReportPanel>
</div>
