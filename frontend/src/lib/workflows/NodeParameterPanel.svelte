<!--
  NodeParameterPanel.svelte — slide-in side panel showing the selected
  node's parameters in a human-readable form.

  Schema-aware path: for every n8n custom node registered in
  `nodeSchemaManifest.ts` (autogenerated), the panel renders each
  property using its declared displayName / type / options /
  displayOptions.show — so the user sees "Resource: Card", not
  "resource: card", and hidden-by-context properties are filtered out
  the same way n8n itself filters them.

  Value-only fallback: for unknown node types (built-in
  `n8n-nodes-base.*` or anything else not bundled), we render the raw
  `parameters` blob as a sorted alphabetical key/value list.

  Read-only — edits go through n8n's UI. ESC closes.
-->
<script lang="ts">
  import type { FlowNode } from './adapter';
  import {
    resolveSchema,
    visibleProperties,
    optionLabel,
    multiOptionLabels,
    formatScalar,
    isLongString,
    valueOnlyRows,
    type ParamProperty,
  } from './parameterRender';

  interface Props {
    node: FlowNode | null;
    onClose: () => void;
  }
  const { node, onClose }: Props = $props();

  function onKey(e: KeyboardEvent) {
    if (e.key === 'Escape') onClose();
  }

  const schema = $derived(node ? resolveSchema(node.data.nodeType) : undefined);
  const params = $derived<Record<string, unknown>>(node ? node.data.parameters : {});
  const visible = $derived(schema ? visibleProperties(schema.properties, params) : []);
  const fallbackRows = $derived(node && !schema ? valueOnlyRows(params) : []);
  const hasAny = $derived(
    schema ? visible.length > 0 : fallbackRows.length > 0,
  );

  function readValue(prop: ParamProperty): unknown {
    if (prop.name in params) return params[prop.name];
    return prop.default;
  }
</script>

<svelte:window onkeydown={onKey} />

{#if node}
  <aside class="panel" aria-label="Node parameters">
    <header>
      <div class="title-block">
        <div class="title">{node.data.name}</div>
        <div class="subtitle" title={node.data.nodeType}>{schema?.displayName ?? node.data.nodeType}</div>
      </div>
      <button type="button" onclick={onClose} aria-label="Close">×</button>
    </header>
    <div class="body">
      {#if !hasAny}
        <p class="empty">No parameters configured.</p>
      {:else if schema}
        <dl class="props">
          {#each visible as prop (prop.name)}
            {@const val = readValue(prop)}
            <div class="row" class:required={prop.required}>
              <dt>
                <span class="label">{prop.displayName}</span>
                {#if prop.required}<span class="req" title="Required">*</span>{/if}
                {#if prop.description}<div class="desc">{prop.description}</div>{/if}
              </dt>
              <dd>
                {#if prop.type === 'boolean'}
                  <span class="chip" class:on={val === true} class:off={val === false}>
                    {val === true ? 'Yes' : val === false ? 'No' : '—'}
                  </span>
                {:else if prop.type === 'options'}
                  <span class="value">{optionLabel(prop, val)}</span>
                {:else if prop.type === 'multiOptions'}
                  {#if Array.isArray(val) && val.length > 0}
                    <div class="chips">
                      {#each multiOptionLabels(prop, val) as label, i (i)}
                        <span class="chip">{label}</span>
                      {/each}
                    </div>
                  {:else}
                    <span class="empty-inline">—</span>
                  {/if}
                {:else if prop.type === 'json'}
                  <pre class="code">{typeof val === 'string' ? val : JSON.stringify(val, null, 2)}</pre>
                {:else if prop.type === 'credentials'}
                  <span class="value mono">credential: {formatScalar(val)}</span>
                {:else if prop.type === 'resourceLocator'}
                  {#if val && typeof val === 'object'}
                    {@const rl = val as { mode?: unknown; value?: unknown }}
                    <span class="value mono">{String(rl.mode ?? 'id')}: {formatScalar(rl.value)}</span>
                  {:else}
                    <span class="value mono">{formatScalar(val)}</span>
                  {/if}
                {:else if prop.type === 'collection' || prop.type === 'fixedCollection'}
                  {#if val && typeof val === 'object' && Object.keys(val as object).length > 0}
                    <details>
                      <summary>{Object.keys(val as object).length} field{Object.keys(val as object).length === 1 ? '' : 's'}</summary>
                      <pre class="code nested">{JSON.stringify(val, null, 2)}</pre>
                    </details>
                  {:else}
                    <span class="empty-inline">—</span>
                  {/if}
                {:else if prop.type === 'notice'}
                  <span class="value muted">{prop.displayName}</span>
                {:else if isLongString(val) || prop.typeOptions?.editor}
                  {#if prop.typeOptions?.editorLanguage}
                    <span class="chip lang">{prop.typeOptions.editorLanguage}</span>
                  {/if}
                  <pre class="code">{val as string}</pre>
                {:else}
                  <span
                    class="value"
                    class:mono={prop.type === 'string' && typeof val === 'string' && val.includes('{{')}
                  >{formatScalar(val)}</span>
                {/if}
              </dd>
            </div>
          {/each}
        </dl>
      {:else}
        <dl class="props value-only">
          {#each fallbackRows as [k, v] (k)}
            <div class="row">
              <dt><span class="label mono">{k}</span></dt>
              <dd>
                {#if isLongString(v)}
                  <pre class="code">{v}</pre>
                {:else}
                  <span class="value mono">{v}</span>
                {/if}
              </dd>
            </div>
          {/each}
        </dl>
      {/if}
    </div>
  </aside>
{/if}

