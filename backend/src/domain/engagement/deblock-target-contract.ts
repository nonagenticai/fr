/**
 * THE DEBLOCK TARGET CONTRACT — fr's prediction of the n8n approval receiver, exported as a
 * byte-stable JSON fixture (spec/deblock-target-contract.json) that ncn's receiver tests
 * against BYTE-FOR-BYTE (vendor it; never hand-edit either copy).
 *
 * Generated ONLY from {@link plannedCardMove} — the same function the decide route answers
 * with — so the fixture cannot describe a table fr does not run. A unit test regenerates it
 * and compares bytes; `bun run scripts/gen-deblock-target-contract.ts` rewrites it.
 *
 * Shape: targets[<case>][<card_type> | "*"] = <list kind> | null (null = the card is held).
 * "*" is every card type outside the proof subset.
 */

import { DEBLOCK_ACTIONS, plannedCardMove } from './deblock-actions';
import { DROPPED_LIST_NAME, PROOF_SUBSET_CARD_TYPES } from './proof-subset';
import { COMPUTED_GATE_RULES } from '../../services/catalogue/card-type-rules';

type Case = {
  key: string;
  decision: string;
  action: string;
  answerText?: string;
  coverageRejectedCount?: number | null;
};

const CASES: Case[] = [
  ...DEBLOCK_ACTIONS.filter((a) => a !== 'COVERAGE').map((a) => ({
    key: `${a}:approved`,
    decision: 'approved',
    action: a,
    ...(a === 'QUESTION' ? { answerText: 'answered' } : {}),
  })),
  { key: 'COVERAGE:approved:none_rejected', decision: 'approved', action: 'COVERAGE', coverageRejectedCount: 0 },
  { key: 'COVERAGE:approved:some_rejected', decision: 'approved', action: 'COVERAGE', coverageRejectedCount: 1 },
  { key: 'COVERAGE:rejected', decision: 'rejected', action: 'COVERAGE', coverageRejectedCount: 2 },
  { key: 'COVERAGE:approved:decision_missing', decision: 'approved', action: 'COVERAGE', coverageRejectedCount: null },
];

export function buildDeblockTargetContract(): Record<string, unknown> {
  const types = [...PROOF_SUBSET_CARD_TYPES, '*'];
  const targets: Record<string, Record<string, string | null>> = {};
  for (const c of CASES) {
    const row: Record<string, string | null> = {};
    for (const t of types) {
      const plan = plannedCardMove({
        decision: c.decision,
        action: c.action,
        answerText: c.answerText,
        // "*" stands for a type outside the proof subset.
        cardType: t === '*' ? 'development_feature_new' : t,
        coverageRejectedCount: c.coverageRejectedCount,
      });
      row[t] = plan.moves ? plan.target : null;
    }
    targets[c.key] = row;
  }
  return {
    $comment:
      'GENERATED by fr backend/scripts/gen-deblock-target-contract.ts from plannedCardMove ' +
      '(backend/src/domain/engagement/deblock-actions.ts). fr is the single truth; ncn ' +
      'approval-callback :: Resolve Target List must match byte-for-byte. null = held. ' +
      '"*" = any card type outside proof_subset_card_types.',
    version: 1,
    dropped_list_name: DROPPED_LIST_NAME,
    proof_subset_card_types: [...PROOF_SUBSET_CARD_TYPES],
    // The computed-gated set is per tenant now: the tenant's RM card types whose
    // `rules[]` hold one of these strings (services/catalogue/card-type-rules.ts).
    computed_gate_rules: [...COMPUTED_GATE_RULES],
    refusals: {
      done_move_without_computed_pass: 'done_without_computed_check',
      reclassify_out_of_computed_gate: 'reclassify_escapes_computed_gate',
    },
    targets,
  };
}

export function serializeDeblockTargetContract(): string {
  return JSON.stringify(buildDeblockTargetContract(), null, 2) + '\n';
}
