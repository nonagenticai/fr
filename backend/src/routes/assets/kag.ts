export async function handleKagListDocuments(req: Request): Promise<Response> {
  const user = await validateAuth(req);
  const url = new URL(req.url);
  const params = parseListKagDocumentsParams(url.searchParams);
  const projectId = url.searchParams.get('project_id') ?? undefined;
  // ⛔ AN EMPTY SET MUST SAY WHY IT IS EMPTY. `applyEffectiveFilter` returns
  // `[]` for a well-formed-but-unknown project_id, and `effective-query.ts`
  // justifies that `[]` ONLY because the route reports the cause out of band:
  // "an empty set WITHOUT that header would be the defect that comment warns
  // about." This route applies that filter, so it owes that header.
  //
  // Resolved HERE rather than inside `handle` because `handle`'s response
  // mapper only receives `data` — it cannot see why the list is short.
  // `projectExists` is the SAME predicate the filter uses, so header and body
  // can never disagree; on a non-UUID it throws the identical
  // `BadRequestError('project_id must be a UUID')` the filter would have
  // thrown one layer down, only earlier and before any upstream call.
  const projectResolved =
    projectId === undefined ? undefined : await projectExists(projectId);
  return handle(
    async () => {
      const upstream = await listKagDocuments(params);
      const filtered = await applyEffectiveFilter(
        ctxTenantId(user.tenantId),
        'kag_document',
        upstream.items,
        projectId,
        user.tenantName,
      );
      // ⚠️ `next_cursor` is NOT forwarded, and that is a fix, not an omission.
      // kag mints it as `str(offset + limit)` whenever the frame comes back
      // full — but the set is read from graph-adapter's `GET /nodes/`, which
      // declares only `label`, `properties` and `envelope`. FastAPI drops the
      // undeclared `limit`/`offset`, so every "page" is the identical full set
      // and a client following the cursor re-requests it forever. Measured
      // live: 559 rows returned alongside `next_cursor: "100"`.
      //
      // `total` stays, and stays a verbatim passthrough. It is null on every
      // call today (kag never sends `envelope=true`), and a null that says
      // "unknown" is the point — never substitute `filtered.length`, which is
      // this page after `applyEffectiveFilter` has dropped rows.
      //
      // To restore a cursor here, graph-adapter's `/nodes/` must first declare
      // `limit`/`offset`; until then there is no page to be next.
      return {
        items: filtered,
        total: upstream.total ?? null,
      };
    },
    (data) => jsonResponse({ data }, 200, projectScopeHeaders(projectResolved)),
  );
}

