// -------- Project scope for cost attribution --------
//
// Owner ruling: when the user has a project open, the kag call carries it as
// `X-Project-Id`; otherwise it carries nothing and kag applies its tenant-level
// fallback (no 400 for an absent project). The id is NEVER forwarded from the
// body: it must first pass the same tenant-scoped resolver every project
// sub-resource uses (`loadTenantScopedProject` → `guardProjectId` →
// `setProjectId`), and `http-client.ts buildHeaders` then reads the
// guard-validated value off the request frame. A foreign, untagged, missing or
// malformed id gets that resolver's uniform don't-leak-existence 404 — the same
// answer `/api/projects/:id/*` gives — and kag is never called.

/** Split an optional `project_id` off a JSON body; the rest goes to kag. */
function splitProjectId(body: unknown): { projectId: unknown; rest: unknown } {
  if (body === null || typeof body !== 'object' || Array.isArray(body)) {
    return { projectId: undefined, rest: body };
  }
  const { project_id: projectId, ...rest } = body as Record<string, unknown>;
  return { projectId, rest };
}

async function scopeKagCallToProject(user: User, projectId: unknown): Promise<void> {
  if (projectId === undefined || projectId === null) return;
  if (typeof projectId !== 'string' || projectId.trim() === '') {
    throw new BadRequestError(
      'project_id must be a non-empty string; omit it to call kag without a project',
    );
  }
  // fr#1499: a kag search/ask is a READ proxied under the project's scope, so
  // it keeps working on an archived project (explicit opt-in to the write lane).
  await loadTenantScopedProject(db, user, projectId.trim(), { allowArchived: true });
}

export async function handleKagSemanticSearch(req: Request): Promise<Response> {
  const user = await validateAuth(req);
  const { projectId, rest: body } = splitProjectId(await readJsonBody(req));
  await scopeKagCallToProject(user, projectId);
  return handle(
    () => semanticSearch(body as Parameters<typeof semanticSearch>[0]),
    (data) => jsonResponse({ data }),
  );
}

