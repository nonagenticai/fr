// Plan 6 W-1 — GET /api/assets/kag/entities
//
// Manifest-shaped wrapper around `queryGraphNodes` so the new KAG
// AssetWorkspace manifest (Wave B, frontend) can list KAG entities the
// same way it lists principles/requirements/decisions/procedures. The
// underlying tenant scoping is identical to /api/assets/kag/graph/nodes
// — the http-client forwards the request-context tenant (which already
// honours the X-Active-Tenant super-admin override) on the upstream
// call.
//
// Response envelope: `{ data: { items: [...], total } }` so AssetList
// can read `body.data.items` consistently with the asset list routes.

interface KagEntityNode {
  id?: string;
  label?: string | null;
  properties?: Record<string, unknown> | null;
}

function normaliseKagNodes(raw: unknown): KagEntityNode[] {
  // KAG's GET /graph/nodes returns either a bare array or `{ items: [...] }`
  // depending on version — accept both. Each node has at minimum `id`;
  // optional `label` + `properties` flow through unchanged for the manifest.
  if (Array.isArray(raw)) return raw as KagEntityNode[];
  if (raw && typeof raw === 'object') {
    const obj = raw as Record<string, unknown>;
    if (Array.isArray(obj.items)) return obj.items as KagEntityNode[];
    if (Array.isArray(obj.nodes)) return obj.nodes as KagEntityNode[];
    if (Array.isArray(obj.data)) return obj.data as KagEntityNode[];
  }
  return [];
}

export async function handleKagListEntities(req: Request): Promise<Response> {
  await validateAuth(req);
  const url = new URL(req.url);
  const params = parseQueryGraphNodesParams(url.searchParams);
  return handle(
    async () => {
      const raw = await queryGraphNodes(params);
      const items = normaliseKagNodes(raw);
      return { items, total: items.length };
    },
    (data) => jsonResponse({ data }),
  );
}

// RAG Q&A — natural-language question over the tenant's KAG. Body must
// contain a non-empty `query`. `mode` is forwarded; upstream defaults if
// omitted. Returns the upstream payload verbatim so the UI can render
// answer + chunks + citations as they arrive.
export async function handleKagAsk(req: Request): Promise<Response> {
  const user = await validateAuth(req);
  const body = await readJsonBody<Partial<KagAskRequest> & { project_id?: unknown }>(req);
  const query = typeof body?.query === 'string' ? body.query.trim() : '';
  if (!query) {
    throw new IntegrationError({
      code: 'BAD_REQUEST',
      message: '`query` is required',
    });
  }
  await scopeKagCallToProject(user, body?.project_id);
  const doc_id =
    typeof body?.doc_id === 'string' && body.doc_id.trim()
      ? body.doc_id.trim()
      : undefined;
  const top_k = typeof body?.top_k === 'number' ? body.top_k : undefined;
  return handle(
    () => askKag({ query, mode: body?.mode, doc_id, top_k }),
    (data) => jsonResponse({ data }),
  );
}

