// ---------- RBAC bridge ----------------------------------------------------
//
// The six job-control verbs below used to call `requireRole(req, 'admin')`,
// which tested ONLY the raw Keycloak claim `user.roles.includes('admin')`. It
// never consulted `workspace-admin` and never read `user_roles` at all, so it
// matched no real grant: the live table holds workspace-admin=12,
// workspace-member=1, and a single `admin` row that is a nil-UUID AUTH_BYPASS
// seed artifact. The gate was therefore closed to every actual administrator.
//
// This is the SAME defect already fixed in routes/channels.ts,
// routes/suggested-schedules.ts and routes/engagements/deliveries.ts — three
// independent sites that each carried their own inline claim-only check. It is
// a recurring SHAPE, not one shared helper, which is why
// scripts/check-admin-claim-only.ts guards the shape rather than a name.
async function requireWorkspaceAdmin(req: Request): Promise<User> {
  const user = await validateAuth(req);
  const ok = await userRolesService.isWorkspaceAdminVia(
    user,
    ctxTenantId(user.tenantId),
    userRolesService.hasRole,
  );
  if (!ok) {
    throw new UnauthorizedError('workspace-admin role required');
  }
  return user;
}

