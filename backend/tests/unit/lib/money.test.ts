// tests/unit/lib/money.test.ts
//
// fr's billed figure must equal what billing-service actually charges.
//
// billing-service is the authority (`billing_service/src/services/billing.py`):
//
//     def apply_markup(internal_usd: Decimal, markup_pct: float) -> Decimal:
//         multiplier = Decimal(str(1 + markup_pct / 100))
//         return (internal_usd * multiplier).quantize(Decimal("0.01"))
//
// fr only DISPLAYS a billed figure, it never persists a charge -- so a mismatch
// is a portal that disagrees with the invoice, not an overcharge. It is still a
// defect: a customer reconciling the two sees different numbers.
//
// MEASURED 2026-09-03 against the OLD implementation
// `(internal * (1 + pct/100)).toFixed(2)`: 2,199 of 40,000 (cost, markup) pairs
// disagreed -- 5.5%, by one cent, in BOTH directions. Two causes: IEEE-754
// binary float vs exact Decimal, and `toFixed` rounding half AWAY FROM ZERO
// where `Decimal.quantize` defaults to ROUND_HALF_EVEN.
//
// The vectors below were generated by running the real Python function and
// recording its output -- they are not hand-computed expectations, so they
// cannot drift into agreeing with a wrong implementation. Every EXPECTED value
// here came out of billing-service's own code.

import { describe, expect, test } from 'bun:test';
import { applyMarkup } from '../../../src/lib/money';

/**
 * [internal_usd, markup_pct, billing-service's answer]
 *
 * The first block is the tie/rounding cases where the old code was WRONG --
 * each of these was a real one-cent disagreement. If someone reverts money.ts
 * to `toFixed`, these go red.
 */
const FROM_BILLING_SERVICE: ReadonlyArray<[string, number, string]> = [
  // --- cases the old toFixed implementation got wrong -----------------------
  ['0.10', 5, '0.10'],
  ['0.50', 5, '0.52'],
  ['0.70', 5, '0.74'],
  ['0.90', 5, '0.94'],
  ['1.30', 5, '1.36'],
  ['1.90', 5, '2.00'],
  ['2.10', 5, '2.20'],
  ['2.50', 5, '2.62'],
  ['3.70', 5, '3.88'],
  ['3.90', 5, '4.10'],
  ['4.30', 5, '4.52'],
  ['4.50', 5, '4.72'],
  // --- ordinary cases, which must not regress ------------------------------
  ['100.00', 25, '125.00'],
  ['1.00', 20, '1.20'],
  ['0.00', 20, '0.00'],
  ['0.42', 0, '0.42'],
  ['19.99', 12.5, '22.49'],
  ['1234.56', 33, '1641.96'],
  ['99999.99', 15, '114999.99'],
  // --- awkward precision: upstream serialises Decimals, not always 2dp -----
  ['0.0001', 10, '0.00'],
  ['0.005', 0, '0.00'],
  ['0.015', 0, '0.02'],
  ['9.995', 0, '10.00'],
];

describe('applyMarkup agrees with billing-service exactly', () => {
  for (const [internal, pct, expected] of FROM_BILLING_SERVICE) {
    test(`${internal} @ ${pct}% -> ${expected}`, () => {
      expect(applyMarkup(internal, pct)).toBe(expected);
    });
  }

  test('ROUND_HALF_EVEN, not half-away-from-zero', () => {
    // The single behaviour that caused 5.5% divergence. `toFixed` would give
    // 0.03 for the first and 0.02 for neither -- ties go to the EVEN cent.
    expect(applyMarkup('0.025', 0)).toBe('0.02');
    expect(applyMarkup('0.035', 0)).toBe('0.04');
  });
});

describe('an unknown markup cannot be expressed as a zero markup', () => {
  // THE DURABLE POINT. The old signature was `(string, number | null)` and
  // returned its input unchanged for null, so every failed markup read billed
  // the tenant AT COST while looking like a legitimate zero-markup tenant.
  // Python's apply_markup has no null path; the TS one was weaker than the
  // contract it claimed to mirror. Callers must now decide, in the open.
  test('null is not an accepted markup', () => {
    // @ts-expect-error — null must not type-check as a markup percentage.
    expect(() => applyMarkup('1.00', null)).toThrow();
  });

  test('a non-finite markup throws rather than silently passing cost through', () => {
    expect(() => applyMarkup('1.00', Number.NaN)).toThrow(TypeError);
    expect(() => applyMarkup('1.00', Number.POSITIVE_INFINITY)).toThrow(TypeError);
  });
});

describe('money is never guessed', () => {
  test('a non-numeral cost throws instead of being passed through', () => {
    // The old code returned the input unchanged for unparseable values, which
    // is the same family of defect: garbage rendered as a real money figure.
    expect(() => applyMarkup('not-a-number', 10)).toThrow(TypeError);
    expect(() => applyMarkup('', 10)).toThrow(TypeError);
  });

  test('negative costs (credits/refunds) still quantize correctly', () => {
    expect(applyMarkup('-1.00', 20)).toBe('-1.20');
  });
});
